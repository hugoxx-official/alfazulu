  // Obtener puntos para abdominales (repeticiones, grupo_edad, sexo)
  static int getSitupsPoints(int reps, int ageGroupIndex, String sex) {
    if (sex == 'M') {
      final table = _situpsMale[ageGroupIndex];
      if (table == null) return 0;

      // Buscar el valor exacto o el más cercano inferior
      for (int r = reps; r >= 0; r--) {
        if (table.containsKey(r)) return table[r]!;
      }
      return 0;
    }
    // TODO: Implementar tabla femenina cuando se disponga de datos
    return 0;
  }

  // Obtener puntos para flexiones (repeticiones, grupo_edad, sexo)
  static int getPushupsPoints(int reps, int ageGroupIndex, String sex) {
    if (sex == 'M') {
      final table = _pushupsMale[ageGroupIndex];
      if (table == null) return 0;

      for (int r = reps; r >= 0; r--) {
        if (table.containsKey(r)) return table[r]!;
      }
      return 0;
    }
    return 0;
  }

  // Obtener puntos para CAV (tiempo en segundos, grupo_edad, sexo)
  static int getCavPoints(double timeSeconds, int ageGroupIndex, String sex) {
    if (sex == 'M') {
      final table = _cavMale[ageGroupIndex];
      if (table == null) return 0;

      // Buscar el tiempo igual o inmediatamente superior (menor tiempo = más puntos)
      final sortedTimes = table.keys.toList()..sort();
      for (final t in sortedTimes) {
        if (timeSeconds <= t) return table[t]!;
      }
      return 0; // Tiempo peor que el mínimo tabulado
    }
    return 0;
  }

  // Obtener puntos para 6000m (tiempo en segundos, grupo_edad, sexo)
  static int getRun6000Points(int timeSeconds, int ageGroupIndex, String sex) {
    if (sex == 'M') {
      final table = _run6000Male[ageGroupIndex];
      if (table == null) return 0;

      // Buscar el tiempo igual o inmediatamente superior
      final sortedTimes = table.keys.toList()..sort();
      for (final t in sortedTimes) {
        if (timeSeconds <= t) return table[t]!;
      }
      // Si supera el máximo tabulado, devolver 0
      return 0;
    }
    return 0;
  }

  // Calcular puntuación total
  static Map<String, dynamic> calculateTotal({
    required int pushups,
    required int situps,
    required double cavTime,
    required int run6000Seconds,
    required int ageGroupIndex,
    required String sex,
  }) {
    final pushupsPoints = getPushupsPoints(pushups, ageGroupIndex, sex);
    final situpsPoints = getSitupsPoints(situps, ageGroupIndex, sex);
    final cavPoints = getCavPoints(cavTime, ageGroupIndex, sex);
    final runPoints = getRun6000Points(run6000Seconds, ageGroupIndex, sex);

    final total = pushupsPoints + situpsPoints + cavPoints + runPoints;
    final maxScore = 400;

    // Nivel y mensaje según puntuación
    String level;
    String message;

    if (total >= 370) {
      level = 'EXCELENTE';
      message = '¡Puntuación excelente! Aptitud máxima para BRIPAC.';
    } else if (total >= 340) {
      level = 'MUY BUENO';
      message = 'Gran condición física. Superas el mínimo para BRIPAC.';
    } else if (total >= 310) {
      level = 'BUENO';
      message = 'Apto para BRIPAC. Sigue entrenando para mejorar.';
    } else if (total >= 280) {
      level = 'REGULAR';
      message = 'Por debajo del mínimo para BRIPAC. Necesitas mejorar.';
    } else {
      level = 'DEFICIENTE';
      message = 'Muy por debajo del mínimo. Intensifica el entrenamiento.';
    }

    return {
      'total': total,
      'max': maxScore,
      'percentage': (total / maxScore * 100).clamp(0, 100),
      'level': level,
      'message': message,
      'details': {
        'Flexiones': {'value': pushups, 'score': pushupsPoints, 'max': 100},
        'Abdominales': {'value': situps, 'score': situpsPoints, 'max': 100},
        'CAV': {'value': '${cavTime.toStringAsFixed(1)}s', 'score': cavPoints, 'max': 100},
        '6000m': {'value': _formatTime(run6000Seconds), 'score': runPoints, 'max': 100},
      },
    };
  }

  static String _formatTime(int seconds) {
    final mins = seconds ~/ 60;
    final secs = seconds % 60;
    return '$mins:${secs.toString().padLeft(2, '0')}';
  }
